--This is the SQL code for creating the table containing the information of the bookshelf

CREATE TABLE bookshelf_database (
  --This is the id of the bookshlef that will be used to distinguish them.
  id SERIAL PRIMARY KEY NOT NULL,

  --This is the name of the booksshelf (eg. "41(A)")
  name text NOT NULL,

  --This is the name of the bookshelf mesh objects
  mesh_name text NOT NULL,

  --This is the location of the bookshelf
  x_pos DOUBLE PRECISION NOT NULL,
  y_pos DOUBLE PRECISION NOT NULL,
  z_pos DOUBLE PRECISION NOT NULL,

  --This is the Rotation of the bookshelf
  x_rot DOUBLE PRECISION NOT NULL,
  y_rot DOUBLE PRECISION NOT NULL,
  z_rot DOUBLE PRECISION NOT NULL,

  --This is the Scale of the bookshelf
  x_sca DOUBLE PRECISION NOT NULL,
  y_sca DOUBLE PRECISION NOT NULL,
  z_sca DOUBLE PRECISION NOT NULL,

  --This will store the range of the books that the bookshelf has
  range_high DOUBLE PRECISION NOT NULL,
  range_low DOUBLE PRECISION NOT NULL,

  --This is the name of the gsap that corresponds to this
  gsap_name text NOT NULL

  --This is the subject this bookshelf contains
  
);

